'use strict';
const assert=require('node:assert/strict');
const flow=require('../workflow-core.js');
let count=0;
function test(name,fn){ fn(); count++; process.stdout.write('✓ '+name+'\n'); }
test('setup initial state',()=>assert.equal(flow.createSession().screen,'setup'));
test('empty start rejected',()=>assert.equal(flow.transition(flow.createSession(),{type:'START',initial:''}).accepted,false));
let s=flow.createSession({scenario:'custom'});
s=flow.transition(s,{type:'START',initial:'优化需求'}).state;
test('start interview',()=>assert.equal(s.screen,'interview'));
test('cannot jump to review',()=>assert.equal(flow.transition(s,{type:'FINISH'}).accepted,false));
test('blank answer rejected',()=>assert.equal(flow.transition(s,{type:'ANSWER',value:' '}).accepted,false));
for(const f of flow.FIELDS)s=flow.transition(s,{type:'ANSWER',value:f==='unknown'?flow.UNKNOWN:'可观察的测试约束'}).state;
test('seven answers lead to challenge',()=>assert.equal(s.screen,'challenge'));
test('cannot finish without choices',()=>assert.equal(flow.transition(s,{type:'FINISH'}).accepted,false));
test('invalid choice target blocked',()=>assert.equal(flow.transition(s,{type:'CHOOSE',field:'screen',value:1}).accepted,false));
s=flow.transition(s,{type:'CHOOSE',field:'stress',value:1}).state;
s=flow.transition(s,{type:'CHOOSE',field:'teachback',value:1}).state;
test('two choices unlock review',()=>assert.equal(flow.canReview(s),true));
s=flow.transition(s,{type:'FINISH'}).state;
test('review reached',()=>assert.equal(s.screen,'review'));
test('invalid restored state rejected',()=>assert.equal(flow.restore({screen:'review',initial:'',scenario:'a',step:6,answers:{},stress:1,teachback:1}),null));
test('valid state restored',()=>assert.equal(flow.restore(s).screen,'review'));
test('no judge calls',()=>assert.equal(flow.rulePrecheck(s).modelCalls,0));
test('no false semantic approval',()=>assert.ok(flow.rulePrecheck(s).checks.every(x=>['UNKNOWN','REVIEW_REQUIRED'].includes(x.decision))));
test('high confidence YES',()=>assert.equal(flow.decideProbability(.90).decision,'YES'));
test('low confidence NO',()=>assert.equal(flow.decideProbability(.10).decision,'NO'));
test('ambiguous UNKNOWN',()=>assert.equal(flow.decideProbability(.5).decision,'UNKNOWN'));
test('invalid probability rejected',()=>assert.throws(()=>flow.decideProbability('yes')));
test('invalid thresholds rejected',()=>assert.throws(()=>flow.decideProbability(.5,{yes:.2,no:.9})));
test('restart clears answers',()=>assert.deepEqual(flow.transition(s,{type:'RESTART'}).state.answers,{}));
console.log(count+' core tests passed');
